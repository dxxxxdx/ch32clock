#!/usr/bin/env python3
"""离线生成页格式数字字模；调整尺寸后运行此脚本，不在 MCU 上逐像素生成。"""
from pathlib import Path


# 字体名称、七段线条的缩放、字模宽度、字模高度。
# 宽度须为 4 的倍数，高度须为 8 的倍数。
FONTS = (("countdownDigits", 3, 20, 40), ("settingDigits", 2, 12, 24))
MASKS = (0x3F, 6, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 7, 0x7F, 0x6F)
BARS = ((1, 0, 4, 1), (5, 1, 1, 4), (5, 6, 1, 4), (1, 10, 4, 1),
        (0, 6, 1, 4), (0, 1, 1, 4), (1, 5, 4, 1))


def glyph_words(width, height, rectangles):
    pixels = bytearray(width * (height // 8))
    for left, top, rect_width, rect_height in rectangles:
        for y in range(top, top + rect_height):
            for x in range(left, left + rect_width):
                pixels[(y // 8) * width + x] |= 1 << (y % 8)
    return [int.from_bytes(pixels[i:i + 4], "little") for i in range(0, len(pixels), 4)]


def generate():
    lines = ['/* Generated by tools/generate_digit_fonts.py; do not edit glyphs by hand. */',
             '#include "digit_font.h"', '']
    for name, scale, width, height in FONTS:
        assert width % 4 == 0 and height % 8 == 0
        assert width >= 6 * scale and height >= 11 * scale
        left, top = (width - 6 * scale) // 2, (height - 11 * scale) // 2
        count = width * height // 32
        lines.append(f'static const uint32_t {name}Data[{10 * count}] = {{')
        for digit, mask in enumerate(MASKS):
            rectangles = [(left + x * scale, top + y * scale, w * scale, h * scale)
                          for bit, (x, y, w, h) in enumerate(BARS) if mask & (1 << bit)]
            words = glyph_words(width, height, rectangles)
            lines.append(f'    /* {digit} */')
            for i in range(0, len(words), width // 4):
                lines.append('        ' + ', '.join(f'0x{w:08x}U' for w in words[i:i + width // 4]) + ',')
        lines.extend(['};', f'const DigitFont {name} = {{',
                      f'    .widthWords = {width // 4},', f'    .pageCount = {height // 8},',
                      f'    .glyphs = {name}Data,', '};', ''])
    height = FONTS[0][3]
    colon = glyph_words(4, height, [(0, height // 4 - 1, 4, 3),
                                    (0, 3 * height // 4 - 1, 4, 3)])
    lines.extend(['const uint32_t countdownColon[] = {',
                  '    ' + ', '.join(f'0x{w:08x}U' for w in colon) + ',', '};', ''])
    target = Path(__file__).resolve().parents[1] / 'App' / 'digit_font.c'
    target.write_text('\n'.join(lines))


if __name__ == '__main__':
    generate()
